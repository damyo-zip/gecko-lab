/** Full-pose art-map compiler. Never writes the original B or production art. */
import {appearanceRuntime} from './appearance-runtime.mjs';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {encodePNG} from './png.mjs';
const check=process.argv.includes('--check'),file='src/lab/appearance/b-breeding/families/art-data.ts';
await appearanceRuntime(async load=>{
 const {FAMILIES,MORPH_FAMILIES,authoredPlan}=await load('lab/appearance/b-breeding/families/art-source');
 const {B_ANATOMY:A}=await load('lab/appearance/b-breeding/anatomy');
 const {insidePolygon}=await load('engine/raster');const frames=[];
 const protect=i=>!A.skin[i]||(((i%96-21)/4.4)**2+((Math.floor(i/96)-25)/5.8)**2<=1);
 for(const m of MORPH_FAMILIES)for(const f of FAMILIES)for(const cadence of ['a','b']){
  const mask=new Uint8Array(9216);
  if(m.id==='lilly')for(let i=0;i<9216;i++)if(A.cream[i]&&!A.head[i]&&!protect(i))mask[i]=4;
  for(const s of authoredPlan(m.id,f.id,cadence))for(let i=0;i<9216;i++)if(!protect(i)&&A[s.region][i]&&(!s.creamOnly||A.cream[i])&&insidePolygon(i%96,Math.floor(i/96),s.path))mask[i]=s.ink;
  const rows=Array.from({length:96},(_,y)=>Array.from(mask.subarray(y*96,y*96+96)).join(''));
  frames.push({id:m.id+':'+f.id+':'+cadence,morph:m.id,family:f.id,cadence,rows});
 }
 const out='/** Generated by compile-b-families.mjs. Frozen full-pose 96px art maps. */\nexport const FAMILY_ART = '+JSON.stringify(frames)+' as const;\n';
 if(check){if(await readFile(file,'utf8')!==out)throw Error('B family art source/export mismatch');}else await writeFile(file,out);
 await mkdir('docs/b-pattern-families/maps',{recursive:true});
 if(!check)for(const f of frames){const p=new Uint8ClampedArray(36864),colors=[[0,0,0,0],[151,95,52,255],[247,209,149,255],[53,33,29,255],[250,245,228,255]];for(let i=0;i<9216;i++)p.set(colors[Number(f.rows[Math.floor(i/96)][i%96])],i*4);await writeFile('docs/b-pattern-families/maps/'+f.id.replaceAll(':','-')+'.png',encodePNG(96,96,p));}
 console.log(JSON.stringify({frames:frames.length,size:'96×96',mode:check?'check':'export'}));
});
