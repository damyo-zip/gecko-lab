/** Technical pixel export of the new art sheet. Never writes production art.
 * Nearest sample → binary alpha → fixed 16-color palette → hard pixel outline.
 * Source concept pixels are NOT shipped as a high-resolution game sprite. */
import sharp from 'sharp';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {encodePNG} from './png.mjs';
import {DESIGNS} from '../src/lab/appearance/base-study/designs.ts';
const folder='public/lab/base-study';
const input=process.argv.slice(2).find(v=>!v.startsWith('--'))??'docs/base-study/source-sheet.png',check=process.argv.includes('--check');
async function save(path,value){if(check){const previous=await readFile(path);if(!previous.equals(Buffer.from(value)))throw Error('Base art export mismatch: '+path);}else await writeFile(path,value);}
const {data,info}=await sharp(await readFile(input)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const {width:w,height:h}=info,n=w*h,seen=new Uint8Array(n),queue=new Int32Array(n),groups=[];
const usable=i=>{
 const k=i*4,r=data[k],g=data[k+1],b=data[k+2];
 return data[k+3]>=192&&!(r>170&&g<85&&r>g*2)&&!(g>r*1.12&&g>80)&&!(r>180&&g>200&&b<65);
};
for(let start=0;start<n;start++)if(!seen[start]&&usable(start)){
 let head=0,tail=1,left=w,right=0,top=h,bottom=0;queue[0]=start;seen[start]=1;
 while(head<tail){const i=queue[head++],x=i%w,y=Math.floor(i/w);left=Math.min(left,x);right=Math.max(right,x);top=Math.min(top,y);bottom=Math.max(bottom,y);
  for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){const xx=x+dx,yy=y+dy,j=yy*w+xx;if(xx>=0&&xx<w&&yy>=0&&yy<h&&!seen[j]&&usable(j)){seen[j]=1;queue[tail++]=j;}}
 }
 if(tail>2000)groups.push({left,right,top,bottom,pixels:queue.slice(0,tail)});
}
const sprites=groups.sort((a,b)=>b.pixels.length-a.pixels.length).slice(0,3).sort((a,b)=>a.left-b.left);
if(sprites.length!==3)throw Error('Expected three independent gecko silhouettes');
await mkdir(folder,{recursive:true});const records=[],manifest=[];
for(const [index,g]of sprites.entries()){
 const id=['A','B','C'][index],cw=g.right-g.left+1,ch=g.bottom-g.top+1,crop=new Uint8ClampedArray(cw*ch*4);
 for(const i of g.pixels){const dest=((Math.floor(i/w)-g.top)*cw+i%w-g.left)*4;crop.set([data[i*4],data[i*4+1],data[i*4+2],255],dest);}
 const small=await sharp(encodePNG(cw,ch,crop)).resize(88,88,{fit:'inside',kernel:'nearest'}).png({palette:true,colours:16,dither:0}).toBuffer();
 const raw=await sharp(small).ensureAlpha().raw().toBuffer({resolveWithObject:true}),pixels=new Uint8ClampedArray(96*96*4),ox=Math.floor((96-raw.info.width)/2),oy=Math.floor((96-raw.info.height)/2);
 for(let y=0;y<raw.info.height;y++)for(let x=0;x<raw.info.width;x++){
  const src=(y*raw.info.width+x)*4,dst=((y+oy)*96+x+ox)*4;if(raw.data[src+3]>=128)pixels.set([raw.data[src],raw.data[src+1],raw.data[src+2],255],dst);
 }
 // Pixel-authored eye cleanup after native sampling. Keep the existing lid and
 // silhouette, but make the vertical pupil and catchlight survive 48/72px.
 const eye=DESIGNS[index].eye;
 for(let y=eye.y-eye.ry;y<=eye.y+eye.ry;y++)for(let x=eye.x-eye.rx;x<=eye.x+eye.rx;x++){
  const d=((x-eye.x)/eye.rx)**2+((y-eye.y)/eye.ry)**2,i=y*96+x;if(d>1||!pixels[i*4+3])continue;
  let c=d>.72?[65,36,25]:x<eye.x?[220,144,55]:[247,185,88];
  if(x===eye.x&&Math.abs(y-eye.y)<eye.ry)c=[30,23,22];
  if(x===eye.x-1&&y===eye.y-eye.ry+2)c=[255,246,219];
  pixels.set([...c,255],i*4);
 }
 // One discrete outer contour helps pads, face and tail read at 48px. No blur.
 const source=pixels.slice();for(let y=1;y<95;y++)for(let x=1;x<95;x++){
  const i=y*96+x;if(!source[i*4+3]&&[-96,-1,1,96].some(d=>source[(i+d)*4+3]))pixels.set([57,34,29,255],i*4);
 }
 const palette=[[0,0,0,0]],lookup=new Map(),indices=[];
 for(let i=0;i<9216;i++){
  if(!pixels[i*4+3]){indices.push(0);continue;}
  const c=[...pixels.subarray(i*4,i*4+4)],key=c.join(',');if(!lookup.has(key)){lookup.set(key,palette.length);palette.push(c);}indices.push(lookup.get(key));
 }
 const rows=Array.from({length:96},(_,y)=>indices.slice(y*96,y*96+96).map(v=>v.toString(36)).join(''));
 if(palette.length>36)throw Error('Palette does not fit base36 indexing');
 records.push(` ${id}:{palette:${JSON.stringify(palette)},rows:${JSON.stringify(rows)}}`);
 const png=encodePNG(96,96,pixels);await save(`${folder}/${id}-normal.png`,png);
 manifest.push({id,width:96,height:96,colors:palette.length-1,alpha:'binary',sourceBounds:{left:g.left,top:g.top,width:cw,height:ch},sha256:createHash('sha256').update(png).digest('hex')});
}
await mkdir('src/lab/appearance/base-study',{recursive:true});
await save('src/lab/appearance/base-study/art-data.ts','/** Generated by scripts/compile-base-study.mjs. Lab-only native indexed pixels. */\nexport const BASE_ART = {\n'+records.join(',\n')+'\n} as const;\n');
await save(folder+'/manifest.json',JSON.stringify({version:'base-study-1',source:'Original AI-assisted art exploration; pixel-constrained export, not a production genetics asset',sprites:manifest},null,2)+'\n');
console.log(JSON.stringify(manifest));
