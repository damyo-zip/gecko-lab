/** Compile committed PNG pixels into a portable browser/Node asset module.
 * PNGs are the source of truth, not decorative exports of coordinate geometry. */
import {readFile,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
import {decodePNG} from "./png.mjs";
const root="art/source/",manifest=JSON.parse(await readFile(root+"manifest.json","utf8"));
const alphabet="0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
const palette=[[0,0,0]],rows={},hashes={};
for(const file of manifest.channels){
 const bytes=await readFile(root+file),png=decodePNG(bytes);if(png.width!==96||png.height!==96)throw new Error("Expected 96px asset: "+file);
 hashes[file]=createHash("sha256").update(bytes).digest("hex");const values=[];
 for(let i=0;i<9216;i++){
  const rgba=png.pixels.subarray(i*4,i*4+4);if(![0,255].includes(rgba[3]))throw new Error("Sprite alpha must be binary");
  if(!rgba[3]){values.push(0);continue;}
  if(file==="normal-base.png"){
   let index=palette.findIndex(p=>p.every((v,j)=>v===rgba[j]));if(index<0){index=palette.length;palette.push([...rgba.subarray(0,3)]);}
   if(index>=alphabet.length)throw new Error("Palette too large");values.push(index);
  }else if(file==="parts.png"){
   const index=manifest.zoneColors.findIndex(p=>p.every((v,j)=>v===rgba[j]));if(index<1)throw new Error("Unknown part color");values.push(index);
  }else values.push(1);
 }
 rows[file.replace(".png","")]=Array.from({length:96},(_,y)=>values.slice(y*96,(y+1)*96).map(v=>alphabet[v]).join(""));
}
const code="// Generated by node scripts/compile-gecko-art.mjs from committed PNGs. Do not edit.\n"+
 "export const ART_PALETTE = "+JSON.stringify(palette)+" as const;\n"+
 "export const ART_ROWS = "+JSON.stringify(rows,null,2)+" as const;\n"+
 "export const ART_ASSET_HASHES = "+JSON.stringify(hashes,null,2)+" as const;\n";
const file="src/core/engine/art-data.ts";
if(process.argv.includes("--check")){if(await readFile(file,"utf8")!==code)throw new Error("Art PNGs and generated runtime data are out of sync");console.log("Art PNG/runtime hashes match.");}
else{await writeFile(file,code);console.log({compiled:manifest.channels.length,paletteColors:palette.length-1,bytes:code.length});}
