import { expect, test } from 'vitest';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { projectRoot } from '../boundary';
import { createFounder, createOffspring } from '../src/engine/individual';
import { calculatePhenotype, describeAppearance } from '../src/engine/appearance';
import { baselineSpecimen, renderAppearance } from '../src/engine/renderer';
import { cross } from '../src/engine/genetics';
import type { Genome, MendelianGenome } from '../src/engine/genetics';
import type { ForgeGecko } from '../src/engine/model';
import type { Forecast } from '../src/core/genetics/advanced/model';
import type { GeckoSpecimen } from '../src/core/engine/model';
import { decodePNG } from '../scripts/png.mjs';

const folder = resolve(projectRoot, 'fixtures/baseline-v1');
const sha = (bytes: Uint8ClampedArray | Buffer) => createHash('sha256').update(bytes).digest('hex');
const json = <T>(name: string) => JSON.parse(readFileSync(resolve(folder, name), 'utf8')) as T;
interface Founder { id: string; seed: string; sex: ForgeGecko['sex']; genome: Genome }
const genetics = json<{founders: Founder[]; families: { fatherId: string; motherId: string; forecast: Forecast; children: { seed: string; genome: Genome }[] }[]}>('genetics.json');
const rendering = json<{ polygenic: Genome['polygenic']; visualSeed: string; cases: { id: string; mendelian: MendelianGenome; fire: 'up'|'down';
  expected: { genetics: ReturnType<typeof calculatePhenotype>['genetics']; traits: ReturnType<typeof calculatePhenotype>['traits']; appearance: GeckoSpecimen['appearance']; observation: ReturnType<typeof describeAppearance>['observation']; rgbaSha256: string }; png: string | null }[] }>('rendering.json');

const founders = new Map(genetics.founders.map(input => [input.id, createFounder({ ...input, mendelian: input.genome.mendelian })]));
function renderCase(c: typeof rendering.cases[number]) {
  const phenotype = calculatePhenotype({ version: 1, mendelian: c.mendelian, polygenic: rendering.polygenic });
  return { phenotype, seed: rendering.visualSeed, fire: c.fire };
}

test('six frozen original founders reproduce every Mendelian and polygenic allele', () => {
  expect(genetics.founders).toHaveLength(6);
  for (const f of genetics.founders) expect(founders.get(f.id)!.genome, f.id).toEqual(f.genome);
});
test('96 frozen offspring and three complete cross forecasts match the original engine', () => {
  expect(genetics.families).toHaveLength(3);
  for (const family of genetics.families) {
    const f = founders.get(family.fatherId)!, m = founders.get(family.motherId)!;
    expect(cross(f.genome.mendelian, m.genome.mendelian)).toEqual(family.forecast);
    expect(family.children).toHaveLength(32);
    for (const [i, c] of family.children.entries()) expect(createOffspring(f, m, { id: 'frozen-' + i, seed: c.seed }).genome, c.seed).toEqual(c.genome);
  }
});
test('120 original phenotype, adapter, observation and exact RGBA baselines remain unchanged', () => {
  expect(rendering.cases).toHaveLength(120);
  for (const c of rendering.cases) {
    const input = renderCase(c), sprite = renderAppearance(input);
    expect(input.phenotype.genetics, c.id).toEqual(c.expected.genetics);
    expect(input.phenotype.traits, c.id).toEqual(c.expected.traits);
    expect(baselineSpecimen(input).appearance, c.id).toEqual(c.expected.appearance);
    expect(describeAppearance(input.phenotype, input.seed).observation, c.id).toEqual(c.expected.observation);
    expect([sprite.width, sprite.height]).toEqual([96,96]);
    expect(sha(sprite.pixels), c.id).toBe(c.expected.rgbaSha256);
  }
});
test('six saved native PNGs contain exactly the original RGBA bytes', () => {
  const cases = rendering.cases.filter(c => c.png); expect(cases).toHaveLength(6);
  for (const c of cases) {
    const png = decodePNG(readFileSync(resolve(folder, c.png!))), sprite = renderAppearance(renderCase(c));
    expect([png.width, png.height]).toEqual([96,96]);
    expect(Buffer.from(png.pixels).equals(Buffer.from(sprite.pixels)), c.png!).toBe(true);
  }
});
test('frozen fixtures are not silently overwritten or regenerated by tests', () => {
  const manifest = json<{ files: { file: string; sha256: string }[] }>('manifest.json');
  for (const item of manifest.files) expect(sha(readFileSync(resolve(folder, item.file))), item.file).toBe(item.sha256);
});
